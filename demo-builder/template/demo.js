/* ───────────────────────────────────────────────────────────────────────────
   Booking demo — generated by the Saturn demo builder

   The treatments are the TREATMENTS array at the top of this file; everything
   else about the clinic is the demo-config block above this script. The flow
   is the Therapy Clinic London one: pick a treatment, pick who, pick a time,
   leave a name and number. Availability is generated in the browser from a
   seeded number, so the diary looks the same on every load but is not real,
   and nothing typed here leaves the page.
   ─────────────────────────────────────────────────────────────────────────── */
(function () {
  'use strict';
  var $ = function (id) { return document.getElementById(id); };
  var el = function (t, c, h) { var e = document.createElement(t);
    if (c) e.className = c; if (h != null) e.innerHTML = h; return e; };
  var esc = function (s) { return String(s == null ? '' : s).replace(/[&<>"']/g, function (c) {
    return { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]; }); };

  var C = JSON.parse($('demo-config').textContent);
  var T = (window.TREATMENTS || []).filter(function (t) { return t && t.name; });
  T.forEach(function (t, i) { t.i = i; });

  /* minutes from midnight, indexed by getDay() (0 is Sunday) */
  var HOURS = C.hours;
  var LEAD = 120;   /* nothing bookable inside two hours */
  var GAP = 10;     /* the room is turned around between clients */

  var TEAM = (C.team || []).map(function (p, i) { p.id = 'p' + i; return p; });
  var STAFF = TEAM.length ? TEAM : [{ id: 'house', name: '' }];
  var canDo = function (p, s) {
    return !s || !p.cats || !p.cats.length || p.cats.indexOf(s.cat) >= 0;
  };
  var byId = function (id) {
    for (var i = 0; i < TEAM.length; i++) if (TEAM[i].id === id) return TEAM[i];
    return null;
  };

  /* the length most of their treatments run to, used before one is chosen */
  var TYPICAL = (function () {
    var n = {}, best = 60, top = 0;
    T.forEach(function (t) { if (t.mins) { n[t.mins] = (n[t.mins] || 0) + 1;
      if (n[t.mins] > top) { top = n[t.mins]; best = t.mins; } } });
    return best;
  })();
  var lenOf = function (s) { return (s && s.mins) || TYPICAL; };

  /* ── state ────────────────────────────────────────────────────────────── */

  var cats = [];
  T.forEach(function (t) { if (cats.indexOf(t.cat) < 0) cats.push(t.cat); });

  var fresh = function () {
    return { cat: cats[0], svc: null, who: TEAM.length ? null : 'any', pid: null,
             day: null, time: null, name: '', tel: '' };
  };
  var S = fresh();
  var svc = function () { return S.svc == null ? null : T[S.svc]; };

  /* ── the diary ────────────────────────────────────────────────────────── */

  var ds = function (d) {
    return d.getFullYear() + '-' + ('0' + (d.getMonth() + 1)).slice(-2) + '-' + ('0' + d.getDate()).slice(-2);
  };
  var parse = function (s) { var p = s.split('-'); return new Date(+p[0], +p[1] - 1, +p[2]); };

  var rng = function (str) {
    var h = 2166136261;
    for (var i = 0; i < str.length; i++) { h ^= str.charCodeAt(i); h = Math.imul(h, 16777619); }
    return function () {
      h = Math.imul(h ^ (h >>> 15), 2246822507); h ^= h >>> 13;
      return (h >>> 0) / 4294967296;
    };
  };

  var shiftsOn = function (dstr) { return HOURS[parse(dstr).getDay()] || []; };
  var stepOn = function (dstr) {
    var open = 0;
    shiftsOn(dstr).forEach(function (s) { open += s[1] - s[0]; });
    return open >= 300 ? 30 : 15;
  };

  /* existing appointments per person per day, derived once so the page is
     stable across renders */
  var cache = {};
  var booked = function (dstr, pid) {
    var key = dstr + pid;
    if (cache[key]) return cache[key];
    var r = rng((C.slug || 'demo') + key), out = [];
    shiftsOn(dstr).forEach(function (sh) {
      var a = sh[0], b = sh[1];
      var load = 0.28 + r() * 0.24;
      var t = a + Math.floor(r() * 3) * 15;
      while (t < b - 20) {
        if (r() < load) {
          var len = [30, 45, 60, 60, 60, 90][Math.floor(r() * 6)];
          if (t + len <= b) { out.push([t, t + len]); t += len + GAP; continue; }
        }
        t += 30;
      }
    });
    cache[key] = out;
    return out;
  };

  var freeFor = function (dstr, s, pid) {
    var mins = lenOf(s), step = stepOn(dstr), busy = booked(dstr, pid);
    var now = new Date();
    var cut = ds(now) === dstr ? now.getHours() * 60 + now.getMinutes() + LEAD : -1;
    var out = [];
    shiftsOn(dstr).forEach(function (sh) {
      for (var t = sh[0]; t + mins <= sh[1]; t += step) {
        if (t < cut) continue;
        var clash = false;
        for (var i = 0; i < busy.length; i++) {
          if (t < busy[i][1] + GAP && busy[i][0] < t + mins + GAP) { clash = true; break; }
        }
        if (!clash) out.push(t);
      }
    });
    return out;
  };

  /* free starts on a day for whoever is chosen; "any" is everyone who does
     that treatment, and each time remembers who would take it */
  var free = function (dstr, s, who) {
    var people = STAFF.filter(function (p) { return canDo(p, s) && (!who || who === 'any' || p.id === who); });
    var seen = {}, out = [];
    people.forEach(function (p) {
      freeFor(dstr, s, p.id).forEach(function (t) {
        if (!(t in seen)) { seen[t] = p.id; out.push(t); }
      });
    });
    out.sort(function (a, b) { return a - b; });
    return out.map(function (t) { return { t: t, pid: seen[t] }; });
  };

  var slotFree = function (dstr, t, s, who) {
    var f = free(dstr, s, who);
    for (var i = 0; i < f.length; i++) if (f[i].t === t) return f[i];
    return null;
  };

  var nextOpening = function (s, who) {
    var d = new Date();
    for (var i = 0; i < 45; i++) {
      var k = ds(d), f = free(k, s, who);
      if (f.length) return { day: k, time: f[0].t, pid: f[0].pid };
      d.setDate(d.getDate() + 1);
    }
    return null;
  };

  /* ── formatting ───────────────────────────────────────────────────────── */

  var DAYS = ['Sunday', 'Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday'];
  var MON = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];

  var hhmm = function (m) {
    var h = Math.floor(m / 60), x = m % 60, ap = h >= 12 ? 'pm' : 'am';
    var hr = h % 12; if (hr === 0) hr = 12;
    return hr + (x ? ':' + ('0' + x).slice(-2) : '') + ap;
  };
  var dayWord = function (dstr) {
    var t = new Date();
    if (ds(t) === dstr) return 'Today';
    t.setDate(t.getDate() + 1);
    if (ds(t) === dstr) return 'Tomorrow';
    return DAYS[parse(dstr).getDay()];
  };
  var dayLong = function (dstr) {
    var d = parse(dstr);
    return dayWord(dstr) + ', ' + d.getDate() + ' ' + MON[d.getMonth()];
  };
  var dur1 = function (m) {
    if (m < 60) return m + ' min';
    if (m === 60) return '1 hour';
    if (m % 60 === 0) return (m / 60) + ' hours';
    return Math.floor(m / 60) + 'h ' + (m % 60) + 'm';
  };
  var dur = function (s) {
    if (!s || !s.mins) return '';
    return s.maxMins && s.maxMins > s.mins ? dur1(s.mins) + ' – ' + dur1(s.maxMins) : dur1(s.mins);
  };
  var gbp = function (p) {
    return '£' + (Math.round(p) === p ? p : p.toFixed(2));
  };
  var money = function (s) {
    if (!s || s.price == null) return '';
    return (s.from ? 'from ' : '') + gbp(s.price);
  };
  var whoName = function (pid) {
    var p = byId(pid);
    return p ? p.name : '';
  };

  var ICON = {
    tick: '<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="3" stroke-linecap="round" stroke-linejoin="round"><path d="M20 6L9 17l-5-5"/></svg>',
    warn: '<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round"><path d="M12 8v5M12 17h.01M10.3 3.9 2.4 17.5A2 2 0 0 0 4.1 20.5h15.8a2 2 0 0 0 1.7-3L13.7 3.9a2 2 0 0 0-3.4 0z"/></svg>',
    any: '<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round"><path d="M9 11a3 3 0 1 0 0-6 3 3 0 0 0 0 6zM3 20a6 6 0 0 1 12 0M16 5.5a3 3 0 0 1 0 5.5M18 14.5a6 6 0 0 1 3 5.5"/></svg>'
  };
  var initials = function (n) {
    var p = String(n).trim().split(/\s+/);
    return ((p[0] || '')[0] || '').toUpperCase() + ((p.length > 1 ? p[p.length - 1][0] : '') || '').toUpperCase();
  };

  /* ── steps ────────────────────────────────────────────────────────────── */

  var STEPS = ['svc', 'who', 'when', 'you'];
  var at = 0;

  var barBottom = function () { var b = $('bar'); return (b ? b.getBoundingClientRect().height : 0) + 12; };

  /* the page scrolls smoothly for anchor links, but landing on the
     confirmation or starting again should be immediate */
  var toTop = function () {
    try { window.scrollTo({ top: 0, behavior: 'instant' }); } catch (e) { window.scrollTo(0, 0); }
  };

  var scrollToY = function (y) {
    y = Math.max(0, Math.round(y));
    var from = window.scrollY;
    if (Math.abs(y - from) < 2) return;
    try { window.scrollTo({ top: y, behavior: 'smooth' }); } catch (e) { window.scrollTo(0, y); }
    setTimeout(function () { if (Math.abs(window.scrollY - from) < 2) window.scrollTo(0, y); }, 220);
  };

  /* Choosing an option folds the step above it into one line, so the next
     question normally comes up to meet you and the page is left alone. Only
     when a long list has folded away from under you is the page moved. */
  var keepInView = function () {
    var box = $('s-' + STEPS[at]);
    if (!box) return;
    var r = box.getBoundingClientRect(), top = barBottom();
    if (r.top < top || r.top > window.innerHeight - 120) scrollToY(r.top + window.scrollY - top);
  };

  var setStep = function (i, follow) {
    if (STEPS[i] === 'who' && !TEAM.length) i++;
    at = i;
    STEPS.forEach(function (k, n) {
      var box = $('s-' + k);
      box.dataset.state = n < i ? 'done' : (n === i ? 'now' : 'wait');
    });
    paint();
    if (follow) keepInView();
  };

  var head = function (n, t) {
    var h = el('div', 'step-h');
    h.innerHTML = '<span class="n">' + n + '</span><h2>' + t + '</h2>';
    return h;
  };
  var fold = function (box, k, v, step) {
    box.innerHTML = '';
    var b = el('button', 'fold');
    b.type = 'button';
    b.innerHTML = '<span class="tick">' + ICON.tick + '</span>' +
      '<span class="fold-t"><span class="fold-k">' + k + '</span>' +
      '<span class="fold-v">' + esc(v) + '</span></span>' +
      (step == null ? '' : '<span class="ch">Change</span>');
    if (step != null) b.onclick = function () { setStep(step); };
    else b.disabled = true;
    box.appendChild(b);
  };

  /* 1 — the treatment */
  var paintSvc = function () {
    var box = $('s-svc');
    if (box.dataset.state === 'done') {
      var s = svc();
      return fold(box, 'Treatment', s.name + (dur(s) ? ' · ' + dur(s) : '') + (money(s) ? ' · ' + money(s) : ''), 0);
    }
    box.innerHTML = '';
    box.appendChild(head(1, 'What can we help with?'));
    var b = el('div', 'step-b');

    if (cats.length > 1) {
      var chips = el('div', 'chips');
      chips.setAttribute('role', 'tablist');
      cats.forEach(function (c) {
        var x = el('button', 'chip', esc(c));
        x.type = 'button';
        x.setAttribute('aria-pressed', S.cat === c);
        x.onclick = function () { S.cat = c; paint(); };
        chips.appendChild(x);
      });
      b.appendChild(chips);
    }

    var g = el('div', 'cards');
    var list = T.filter(function (t) { return cats.length < 2 || t.cat === S.cat; });
    list.forEach(function (s) {
      var c = el('button', 'card');
      c.type = 'button';
      if (S.svc === s.i) c.dataset.on = '1';
      var price = s.price == null ? '' :
        (s.was && s.was > s.price ? '<s>' + gbp(s.was) + '</s>' : '') +
        (s.from ? '<small>from</small>' : '') + gbp(s.price);
      c.innerHTML =
        '<span class="card-top"><span class="card-n">' + esc(s.name) + '</span>' +
        (price ? '<span class="card-p">' + price + '</span>' : '') + '</span>' +
        (dur(s) ? '<span class="card-m" style="display:block">' + dur(s) + '</span>' : '') +
        (s.desc ? '<span class="card-d" style="display:block">' + esc(s.desc) + '</span>' : '');
      c.onclick = function () {
        S.svc = s.i;
        if (S.who && S.who !== 'any' && !canDo(byId(S.who), s)) S.who = null;
        /* if they came in off "take this one", keep that slot when the
           treatment still fits it, and go straight to their details */
        var held = S.day && S.time != null ? slotFree(S.day, S.time, s, S.who || 'any') : null;
        if (held) { S.pid = held.pid; if (!S.who) S.who = 'any'; setStep(3, true); }
        else { S.day = null; S.time = null; S.pid = null; setStep(S.who && TEAM.length ? 2 : 1, true); }
      };
      g.appendChild(c);
    });
    b.appendChild(g);

    var noted = list.filter(function (t) { return t.note; });
    if (noted.length) {
      var w = el('div', 'must');
      w.innerHTML = ICON.warn + '<span>' + noted.map(function (t) {
        return '<b>' + esc(t.name) + ':</b> ' + esc(t.note); }).join('<br>') + '</span>';
      b.appendChild(w);
    }

    var msg = S.day && S.time != null
      ? 'Holding ' + dayLong(S.day) + ' at ' + hhmm(S.time) + ' while you choose.'
      : 'Not sure which? Pick the closest and the clinic will check with you before your visit.';
    b.appendChild(el('p', 'fine', msg));
    box.appendChild(b);
  };

  /* 2 — who */
  var paintWho = function () {
    var box = $('s-who');
    if (!TEAM.length) {
      if (box.dataset.state === 'wait') { box.innerHTML = ''; box.appendChild(head(2, 'Who would you like to see?')); return; }
      return fold(box, 'With', 'Any available practitioner', null);
    }
    if (box.dataset.state === 'done') {
      return fold(box, 'With', S.who === 'any' ? (S.pid && byId(S.pid) ? whoName(S.pid) + ' (first available)' : 'Whoever is free first') : whoName(S.who), 1);
    }
    box.innerHTML = '';
    box.appendChild(head(2, 'Who would you like to see?'));
    if (box.dataset.state === 'wait') return;
    var b = el('div', 'step-b'), g = el('div', 'opts');
    var s = svc();
    var rows = [{ id: 'any', n: 'Whoever is free first', sub: 'Gets you in soonest' }]
      .concat(TEAM.filter(function (p) { return canDo(p, s); })
        .map(function (p) { return { id: p.id, n: p.name, sub: p.role || '' }; }));
    rows.forEach(function (r) {
      var o = el('button', 'opt');
      o.type = 'button';
      o.setAttribute('aria-pressed', S.who === r.id);
      o.innerHTML = '<span class="av">' + (r.id === 'any' ? ICON.any : esc(initials(r.n))) + '</span>' +
        '<span class="opt-t"><b class="opt-n">' + esc(r.n) + '</b>' +
        (r.sub ? '<span class="opt-s">' + esc(r.sub) + '</span>' : '') + '</span>';
      o.onclick = function () {
        S.who = r.id;
        var held = S.day && S.time != null ? slotFree(S.day, S.time, s, r.id) : null;
        if (held) { S.pid = held.pid; setStep(3, true); }
        else { S.day = null; S.time = null; S.pid = null; setStep(2, true); }
      };
      g.appendChild(o);
    });
    b.appendChild(g);
    box.appendChild(b);
  };

  /* 3 — when */
  var PARTS = [['Morning', 0, 720], ['Afternoon', 720, 1020], ['Evening', 1020, 1440]];
  var paintWhen = function () {
    var box = $('s-when');
    if (box.dataset.state === 'done') return fold(box, 'Appointment', dayLong(S.day) + ' at ' + hhmm(S.time), 2);
    box.innerHTML = '';
    box.appendChild(head(3, 'When suits you?'));
    if (box.dataset.state === 'wait') return;
    var b = el('div', 'step-b'), s = svc();

    var strip = el('div', 'days'), d = new Date(), first = null;
    for (var i = 0; i < 14; i++) {
      var k = ds(d), n = free(k, s, S.who).length;
      if (n && !first) first = k;
      var open = shiftsOn(k).length > 0;
      var btn = el('button', 'day');
      btn.type = 'button';
      btn.disabled = !n;
      btn.innerHTML = '<i>' + DAYS[d.getDay()].slice(0, 3) + '</i><b>' + d.getDate() + '</b>' +
        '<em>' + (n ? n + ' free' : (!open ? 'closed' : (ds(new Date()) === k ? 'too late' : 'full'))) + '</em>';
      btn.dataset.k = k;
      (function (kk) { btn.onclick = function () { S.day = kk; S.time = null; paint(); }; })(k);
      strip.appendChild(btn);
      d.setDate(d.getDate() + 1);
    }
    if (!S.day || !free(S.day, s, S.who).length) S.day = first;
    Array.prototype.forEach.call(strip.children, function (x) { x.setAttribute('aria-pressed', x.dataset.k === S.day); });
    b.appendChild(strip);

    var f = S.day ? free(S.day, s, S.who) : [];
    if (!f.length) {
      b.appendChild(el('div', 'none', '<b>Nothing free in the next two weeks.</b>' +
        (C.phone ? 'Ring the clinic on ' + esc(C.phone) + ' and they will fit you in.' : 'Try another practitioner.')));
    }
    PARTS.forEach(function (p) {
      var these = f.filter(function (x) { return x.t >= p[1] && x.t < p[2]; });
      if (!these.length) return;
      var w = el('div', 'part');
      w.appendChild(el('div', 'part-k', p[0]));
      var g = el('div', 'times');
      these.forEach(function (x) {
        var t = el('button', 'time', hhmm(x.t));
        t.type = 'button';
        t.setAttribute('aria-pressed', S.time === x.t);
        t.onclick = function () { S.time = x.t; S.pid = x.pid; setStep(3, true); };
        g.appendChild(t);
      });
      w.appendChild(g);
      b.appendChild(w);
    });
    box.appendChild(b);
  };

  /* 4 — who you are */
  var paintYou = function () {
    var box = $('s-you');
    if (box.dataset.state === 'wait') { box.innerHTML = ''; box.appendChild(head(4, 'Last thing')); return; }
    if (box.querySelector('.fields')) return;   /* keep what they typed */
    box.innerHTML = '';
    box.appendChild(head(4, 'Last thing'));
    var b = el('div', 'step-b'), f = el('div', 'fields');
    f.innerHTML =
      '<div class="f" id="f-name"><label for="i-name">Your name</label>' +
      '<input id="i-name" type="text" autocomplete="name" enterkeyhint="next" placeholder="First and last name">' +
      '<span class="err">We need a name for the appointment</span></div>' +
      '<div class="f" id="f-tel"><label for="i-tel">Mobile</label>' +
      '<input id="i-tel" type="tel" autocomplete="tel" inputmode="tel" enterkeyhint="done" placeholder="07…">' +
      '<span class="err">A mobile number, so we can text you the confirmation</span></div>';
    b.appendChild(f);
    var notes = [];
    var s = svc();
    if (s && s.note) notes.push('<b>Please note:</b> ' + esc(s.note));
    if (C.note) notes.push('<b>Please note:</b> ' + esc(C.note));
    notes.forEach(function (n) {
      var w = el('div', 'must');
      w.innerHTML = ICON.warn + '<span>' + n + '</span>';
      b.appendChild(w);
    });
    b.appendChild(el('p', 'fine', esc(C.reassure)));
    box.appendChild(b);
    $('i-name').value = S.name; $('i-tel').value = S.tel;
    $('i-name').oninput = function () { S.name = this.value; $('f-name').removeAttribute('data-bad'); };
    $('i-tel').oninput = function () { S.tel = this.value; $('f-tel').removeAttribute('data-bad'); };
    $('i-name').onkeydown = function (e) { if (e.key === 'Enter') $('i-tel').focus(); };
    $('i-tel').onkeydown = function (e) { if (e.key === 'Enter') confirmIt(); };
  };

  /* ── summary: a dock on phones, a panel beside the flow on wide screens ── */

  var withTxt = function () {
    if (!TEAM.length) return S.svc != null ? 'Any available' : null;
    if (!S.who) return null;
    if (S.who === 'any') return S.pid && S.time != null ? whoName(S.pid) : 'Whoever is free first';
    return whoName(S.who);
  };
  var whenTxt = function () { return S.day && S.time != null ? dayLong(S.day) + ', ' + hhmm(S.time) : null; };
  var ready = function () { return at === 3 && S.svc != null && S.day && S.time != null; };

  var summary = function () {
    var s = svc();
    var d = $('dock');
    d.hidden = !s;
    if (s) {
      $('dock-t').innerHTML = '<span class="dock-k">Your booking</span><b>' + esc(s.name) + '</b>' +
        '<span>' + esc(whenTxt() || [dur(s), money(s)].filter(Boolean).join(' · ')) + '</span>';
      $('dock-b').hidden = !ready();
    }
    var rows = $('rail-rows');
    rows.innerHTML = '';
    [['Treatment', s ? s.name : null], ['With', withTxt()], ['When', whenTxt()]].forEach(function (r) {
      var x = el('div');
      x.innerHTML = '<dt>' + r[0] + '</dt><dd class="' + (r[1] ? '' : 'dim') + '">' + esc(r[1] || 'Not yet') + '</dd>';
      rows.appendChild(x);
    });
    $('rail-total').textContent = s ? (money(s) || 'Pay at the clinic') : '—';
    $('rail-dur').textContent = s ? [dur(s), s.price != null ? 'pay at the clinic' : ''].filter(Boolean).join(' · ') : '';
    $('rail-b').disabled = !ready();
  };

  var confirmIt = function () {
    if (!ready()) return;
    var ok = true;
    if (!S.name.trim()) { $('f-name').dataset.bad = '1'; ok = false; }
    if (S.tel.replace(/\D/g, '').length < 10) { $('f-tel').dataset.bad = '1'; ok = false; }
    if (!ok) { ($('f-name').dataset.bad ? $('i-name') : $('i-tel')).focus(); return; }

    var s = svc();
    $('r-what').textContent = s.name + (dur(s) ? ' (' + dur(s) + ')' : '');
    $('r-when').textContent = dayLong(S.day) + ' at ' + hhmm(S.time);
    $('r-who').textContent = withTxt() || 'Any available';
    $('r-cost').textContent = s.price != null ? money(s) + ', pay at the clinic' : 'Confirmed at the clinic';
    $('r-tel').textContent = S.tel.trim();
    $('r-tel2').textContent = S.tel.trim();
    var notes = [s.note, C.note].filter(Boolean);
    $('r-note').textContent = notes.join(' ');
    $('r-note').parentNode.hidden = !notes.length;
    /* kept in this browser only, so the clinic's dashboard demo can show
       the booking arriving; nothing is sent anywhere */
    try {
      var key = 'srdemo:' + C.slug, list = JSON.parse(localStorage.getItem(key) || '[]') || [];
      list.push({ name: S.name.trim(), svc: s.name, mins: s.mins || null, price: s.price, day: S.day, time: S.time,
        with: S.pid && byId(S.pid) ? byId(S.pid).name : '', at: Date.now() });
      localStorage.setItem(key, JSON.stringify(list.slice(-5)));
    } catch (e) {}
    document.body.dataset.done = '1';
    stick();
    toTop();
  };

  var again = function () {
    S = fresh();
    document.body.dataset.done = '';
    $('s-you').innerHTML = '';
    paintHero();
    setStep(0);
    toTop();
  };

  /* ── hero ─────────────────────────────────────────────────────────────── */

  var paintHero = function () {
    var n = nextOpening(null, 'any');
    var box = $('soon');
    if (!n) { box.hidden = true; return; }
    $('soon-when').textContent = dayLong(n.day) + ', ' + hhmm(n.time);
    $('soon-what').textContent = TEAM.length > 1 && byId(n.pid)
      ? 'With ' + whoName(n.pid) + '. Pick your treatment and it’s yours.'
      : 'Pick your treatment and it’s yours.';
    $('soon-take').onclick = function () {
      S.day = n.day; S.time = n.time; S.pid = n.pid;
      if (TEAM.length) S.who = 'any';
      setStep(0);
      scrollToY($('flow').getBoundingClientRect().top + window.scrollY - barBottom());
    };
  };

  /* ── boot ─────────────────────────────────────────────────────────────── */

  var paint = function () { paintSvc(); paintWho(); paintWhen(); paintYou(); summary(); };

  var stick = function () {
    var b = $('bar');
    if (window.scrollY > 4 || document.body.dataset.done === '1') b.setAttribute('data-stuck', '1');
    else b.removeAttribute('data-stuck');
  };

  var today = new Date().getDay();
  Array.prototype.forEach.call(document.querySelectorAll('.f-hrs [data-d]'), function (r) {
    if (+r.dataset.d === today) r.setAttribute('data-today', '1');
  });

  if (!T.length) {
    $('s-svc').innerHTML = '<div class="step-b"><div class="none"><b>No treatments yet.</b>Add some in the builder.</div></div>';
    $('soon').hidden = true;
    return;
  }
  paintHero();
  setStep(0);
  $('dock-b').onclick = confirmIt;
  $('rail-b').onclick = confirmIt;
  $('again').onclick = again;
  window.addEventListener('scroll', stick, { passive: true });
  stick();
})();
