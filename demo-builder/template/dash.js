/* ───────────────────────────────────────────────────────────────────────────
   Owner dashboard — generated by the Saturn demo builder

   Every appointment here is an example, but it is built from the clinic's
   own treatments, prices, team and opening hours, and from the same seeded
   diary as their booking page: the times that page shows as taken are the
   appointments listed here. A booking made on the booking page in this
   browser is saved in this browser only and shows up here as new.
   ─────────────────────────────────────────────────────────────────────────── */
(function () {
  'use strict';
  var $ = function (id) { return document.getElementById(id); };
  var el = function (t, c, h) { var e = document.createElement(t); if (c) e.className = c; if (h != null) e.innerHTML = h; return e; };
  var esc = function (s) { return String(s == null ? '' : s).replace(/[&<>"']/g, function (c) {
    return { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]; }); };

  var C = JSON.parse($('demo-config').textContent);
  var T = (window.TREATMENTS || []).filter(function (t) { return t && t.name; });
  var HOURS = C.hours;
  var GAP = 10;
  var TEAM = (C.team || []).map(function (p, i) { p.id = 'p' + i; return p; });
  var STAFF = TEAM.length ? TEAM : [{ id: 'house', name: '' }];
  var canDo = function (p, s) { return !s || !p.cats || !p.cats.length || p.cats.indexOf(s.cat) >= 0; };
  var priced = T.some(function (t) { return t.price != null; });

  /* ── the diary: these four must stay the same as in the booking page ──── */

  var ds = function (d) {
    return d.getFullYear() + '-' + ('0' + (d.getMonth() + 1)).slice(-2) + '-' + ('0' + d.getDate()).slice(-2);
  };
  var parse = function (s) { var p = s.split('-'); return new Date(+p[0], +p[1] - 1, +p[2]); };
  var rng = function (str) {
    var h = 2166136261;
    for (var i = 0; i < str.length; i++) { h ^= str.charCodeAt(i); h = Math.imul(h, 16777619); }
    return function () {
      h = Math.imul(h ^ (h >>> 15), 2246822507); h ^= h >>> 13;
      return (h >>> 0) / 4294967296;
    };
  };
  var shiftsOn = function (dstr) { return HOURS[parse(dstr).getDay()] || []; };
  var cache = {};
  var booked = function (dstr, pid) {
    var key = dstr + pid;
    if (cache[key]) return cache[key];
    var r = rng((C.slug || 'demo') + key), out = [];
    shiftsOn(dstr).forEach(function (sh) {
      var a = sh[0], b = sh[1];
      var load = 0.28 + r() * 0.24;
      var t = a + Math.floor(r() * 3) * 15;
      while (t < b - 20) {
        if (r() < load) {
          var len = [30, 45, 60, 60, 60, 90][Math.floor(r() * 6)];
          if (t + len <= b) { out.push([t, t + len]); t += len + GAP; continue; }
        }
        t += 30;
      }
    });
    cache[key] = out;
    return out;
  };

  /* ── appointments ─────────────────────────────────────────────────────── */

  var NAMES = ['Sarah', 'James', 'Aisha', 'Tom', 'Priya', 'Daniel', 'Emma', 'Mohammed', 'Chloe', 'Ryan', 'Fatima', 'Jack',
    'Sophie', 'Adam', 'Hannah', 'Yusuf', 'Olivia', 'Liam', 'Zara', 'Ben', 'Grace', 'Omar', 'Lucy', 'Kieran', 'Amira', 'Josh',
    'Ella', 'Hassan', 'Megan', 'Luke', 'Nadia', 'Sam', 'Holly', 'Ibrahim', 'Jess', 'Callum', 'Leah', 'Bilal', 'Rachel', 'Dan'];
  var INITIAL = 'ABCDEFGHJKLMNPRSTW';
  var now = new Date();
  var nowMin = now.getHours() * 60 + now.getMinutes();
  var TODAY = ds(now);
  var at = function (dstr, m) { var d = parse(dstr); d.setMinutes(m); return d; };

  var local = [];
  try { local = JSON.parse(localStorage.getItem('srdemo:' + C.slug) || '[]') || []; } catch (e) { local = []; }

  var memo = {};
  var apptsOn = function (dstr) {
    if (memo[dstr]) return memo[dstr];
    var out = [];
    /* past a fortnight a real diary thins out, so keep fewer the further
       ahead it is; the next two weeks stay exactly as the booking page has them */
    var ahead = Math.round((parse(dstr) - parse(TODAY)) / 864e5);
    var keep = ahead > 14 ? Math.max(0.1, 1 - (ahead - 14) / 30) : 1;
    STAFF.forEach(function (p) {
      var r = rng('dash' + (C.slug || '') + dstr + p.id), thin = rng('thin' + (C.slug || '') + dstr + p.id);
      booked(dstr, p.id).forEach(function (iv) {
        if (thin() > keep) return;
        var len = iv[1] - iv[0];
        var pool = T.filter(function (t) { return canDo(p, t); });
        if (!pool.length) pool = T;
        var gap = function (t) { return Math.abs((t.mins || 60) - len); };
        var best = Math.min.apply(null, pool.map(gap));
        var near = pool.filter(function (t) { return gap(t) === best; });
        var t = near.length ? near[Math.floor(r() * near.length)] : { name: 'Appointment', mins: len, price: null };
        var start = at(dstr, iv[0]);
        var made = new Date(start.getTime() - (1 + Math.floor(r() * r() * 11)) * 864e5);
        made.setHours(0, Math.floor(r() * 1440), 0, 0);
        if (made > now) made = new Date(now.getTime() - (20 + Math.floor(r() * 600)) * 6e4);
        if (made > start) made = new Date(start.getTime() - 36e5 * 3);
        out.push({
          day: dstr, start: iv[0], end: iv[1], t: t, pid: p.id, made: made, online: r() < 0.74,
          who: NAMES[Math.floor(r() * NAMES.length)] + ' ' + INITIAL[Math.floor(r() * INITIAL.length)] + '.'
        });
      });
    });
    local.forEach(function (b) {
      if (b.day !== dstr) return;
      var p = TEAM.filter(function (x) { return x.name === b.with; })[0];
      var t = T.filter(function (x) { return x.name === b.svc; })[0] || { name: b.svc, mins: b.mins, price: b.price };
      out.push({ day: dstr, start: b.time, end: b.time + (t.mins || 60), t: t, pid: p ? p.id : STAFF[0].id,
        made: new Date(b.at), online: true, who: b.name, fresh: true });
    });
    out.sort(function (a, b) { return a.start - b.start || (a.pid < b.pid ? -1 : 1); });
    memo[dstr] = out;
    return out;
  };
  var range = function (from, days) {
    var out = [], d = parse(from);
    for (var i = 0; i < days; i++) { out = out.concat(apptsOn(ds(d))); d.setDate(d.getDate() + 1); }
    return out;
  };
  var shift = function (dstr, n) { var d = parse(dstr); d.setDate(d.getDate() + n); return ds(d); };
  var done = function (a) { return a.day < TODAY || (a.day === TODAY && a.end <= nowMin); };
  var value = function (a) { return a.t.price || 0; };
  var sum = function (xs) { return xs.reduce(function (s, a) { return s + value(a); }, 0); };

  /* the week runs Monday to Sunday */
  var monday = function (dstr) { var d = parse(dstr), g = (d.getDay() + 6) % 7; d.setDate(d.getDate() - g); return ds(d); };
  var closedAt = function (d) {
    var m = d.getHours() * 60 + d.getMinutes();
    var sh = HOURS[d.getDay()] || [];
    return !sh.some(function (s) { return m >= s[0] && m < s[1]; });
  };

  /* ── formatting ───────────────────────────────────────────────────────── */

  var DAYS = ['Sunday', 'Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday'];
  var MON = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
  var MONTHS = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];
  var hhmm = function (m) {
    var h = Math.floor(m / 60), x = m % 60, ap = h >= 12 ? 'pm' : 'am';
    var hr = h % 12; if (hr === 0) hr = 12;
    return hr + (x ? ':' + ('0' + x).slice(-2) : '') + ap;
  };
  var clock = function (d) { return hhmm(d.getHours() * 60 + d.getMinutes()); };
  var gbp = function (n) { return '£' + Math.round(n).toLocaleString('en-GB'); };
  var dayShort = function (dstr) {
    if (dstr === TODAY) return 'Today';
    if (dstr === shift(TODAY, 1)) return 'Tomorrow';
    var d = parse(dstr);
    return DAYS[d.getDay()].slice(0, 3) + ' ' + d.getDate() + ' ' + MON[d.getMonth()];
  };
  var ago = function (d) {
    var m = Math.round((now - d) / 6e4);
    if (m < 2) return 'just now';
    if (m < 60) return m + ' min ago';
    var h = Math.round(m / 60);
    if (h < 24) return h + (h === 1 ? ' hour ago' : ' hours ago');
    var n = Math.round(h / 24);
    return n === 1 ? 'yesterday' : n + ' days ago';
  };
  var staffName = function (pid) { var p = TEAM.filter(function (x) { return x.id === pid; })[0]; return p ? p.name : ''; };
  var initials = function (n) { var p = String(n).replace(/\./g, '').trim().split(/\s+/); return ((p[0] || '')[0] || '') + ((p[1] || '')[0] || ''); };

  var ICON = {
    up: '<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="3" stroke-linecap="round" stroke-linejoin="round"><path d="M12 19V5M5 12l7-7 7 7"/></svg>',
    down: '<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="3" stroke-linecap="round" stroke-linejoin="round"><path d="M12 5v14M19 12l-7 7-7-7"/></svg>',
    bell: '<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2.2" stroke-linecap="round" stroke-linejoin="round"><path d="M18 8a6 6 0 0 0-12 0c0 7-3 9-3 9h18s-3-2-3-9M13.7 21a2 2 0 0 1-3.4 0"/></svg>'
  };

  /* ── hello ────────────────────────────────────────────────────────────── */

  var part = now.getHours() < 12 ? 'morning' : (now.getHours() < 18 ? 'afternoon' : 'evening');
  $('hello').textContent = 'Good ' + part + (C.owner ? ', ' + C.owner : '');
  var todays = apptsOn(TODAY);
  $('today-line').textContent = DAYS[now.getDay()] + ' ' + now.getDate() + ' ' + MONTHS[now.getMonth()] + ' · ' +
    (shiftsOn(TODAY).length ? todays.length + ' appointment' + (todays.length === 1 ? '' : 's') + ' today' : 'closed today');

  var fresh = local.slice().sort(function (a, b) { return b.at - a.at; })[0];
  if (fresh) {
    var n = $('new');
    n.hidden = false;
    n.innerHTML = '<span class="new-i">' + ICON.bell + '</span><div><b>New booking: ' + esc(fresh.name) + '</b>' +
      '<span>' + esc(fresh.svc) + ', ' + esc(dayShort(fresh.day)) + ' at ' + hhmm(fresh.time) +
      (fresh.with ? ' with ' + esc(fresh.with) : '') + '. Booked online ' + ago(new Date(fresh.at)) + '.</span></div>';
  }

  /* ── tiles ────────────────────────────────────────────────────────────── */

  var wk = monday(TODAY);
  var thisWeek = range(wk, 7), lastWeek = range(shift(wk, -7), 7);
  var onlineWk = thisWeek.filter(function (a) { return a.online; });
  var closedWk = onlineWk.filter(function (a) { return closedAt(a.made); });
  var nextOpen = TODAY;
  for (var k = 0; k < 14 && !shiftsOn(nextOpen).length; k++) nextOpen = shift(nextOpen, 1);

  var tiles = [];
  if (shiftsOn(TODAY).length) {
    tiles.push(['Today', todays.length, priced ? gbp(sum(todays)) + ' booked in' : 'appointments booked in']);
  } else {
    var nx = apptsOn(nextOpen);
    tiles.push([dayShort(nextOpen), nx.length, 'booked in. Closed today']);
  }
  if (priced) {
    var a1 = sum(thisWeek), a0 = sum(lastWeek), pct = a0 ? Math.round((a1 - a0) / a0 * 100) : 0;
    tiles.push(['This week', gbp(a1), (a0 ? '<span class="delta' + (pct >= 0 ? ' up' : '') + '">' + (pct >= 0 ? ICON.up : ICON.down) +
      Math.abs(pct) + '%</span> on last week' : 'booked so far')]);
  } else {
    tiles.push(['This week', thisWeek.length, 'appointments booked']);
  }
  tiles.push(['Booked online', onlineWk.length, closedWk.length ? closedWk.length + ' while you were closed' : 'this week, no phone calls']);
  tiles.push(['Texts sent', thisWeek.length * 2, 'confirmations and reminders, sent for you']);
  $('tiles').innerHTML = tiles.map(function (t) {
    return '<div class="tile"><div class="tile-k">' + esc(t[0]) + '</div><div class="tile-v">' + esc(t[1]) + '</div><div class="tile-s">' + t[2] + '</div></div>';
  }).join('');

  /* ── calendar ─────────────────────────────────────────────────────────── */

  /* Each person keeps a colour so a week reads at a glance. Only the first
     three slots of the validated categorical palette stay distinguishable
     pair by pair, colour-blind or not, so with more than three people the
     calendar uses the brand colour and shows one person at a time on request.
     Names are always on the bookings, so colour is never the only clue. */
  var SERIES = ['#2A78D6', '#EB6834', '#1BAF7A'];
  var coloured = TEAM.length >= 2 && TEAM.length <= 3;
  var hueOf = function (pid) {
    var i = TEAM.map(function (p) { return p.id; }).indexOf(pid);
    return coloured && SERIES[i] ? SERIES[i] : 'var(--accent)';
  };
  var paint = function (node, pid, fresh) {
    var c = fresh ? 'var(--good)' : hueOf(pid);
    node.style.borderLeftColor = c;
    node.style.background = 'color-mix(in srgb, ' + c + ' 13%, var(--raise))';
  };

  var cal = {
    view: window.innerWidth >= 700 ? 'week' : 'day',
    anchor: shiftsOn(TODAY).length ? TODAY : nextOpen,
    /* past three people "Everyone" is too crowded to start on */
    who: TEAM.length > 3 ? TEAM[0].id : 'all'
  };
  var mine = function (list) { return cal.who === 'all' ? list : list.filter(function (a) { return a.pid === cal.who; }); };
  var people = function () { return cal.who === 'all' ? STAFF : STAFF.filter(function (p) { return p.id === cal.who; }); };
  var isPast = function (a) { return a.day < TODAY || (a.day === TODAY && a.end <= nowMin); };
  var monthStart = function (dstr) { var d = parse(dstr); return ds(new Date(d.getFullYear(), d.getMonth(), 1)); };

  var label = function () {
    var d = parse(cal.anchor);
    if (cal.view === 'day') return DAYS[d.getDay()] + ' ' + d.getDate() + ' ' + MONTHS[d.getMonth()] + (cal.anchor === TODAY ? ' · Today' : '');
    if (cal.view === 'month') return MONTHS[d.getMonth()] + ' ' + d.getFullYear();
    var a = parse(monday(cal.anchor)), b = parse(shift(monday(cal.anchor), 6));
    return a.getDate() + (a.getMonth() !== b.getMonth() ? ' ' + MON[a.getMonth()] : '') + ' – ' + b.getDate() + ' ' + MON[b.getMonth()] + ' ' + b.getFullYear();
  };
  var move = function (n) {
    if (cal.view === 'day') cal.anchor = shift(cal.anchor, n);
    else if (cal.view === 'week') cal.anchor = shift(cal.anchor, 7 * n);
    else { var d = parse(cal.anchor); cal.anchor = ds(new Date(d.getFullYear(), d.getMonth() + n, 1)); }
    paintCal();
  };

  /* overlapping bookings sit side by side, the way a calendar app lays them out */
  var lanes = function (list) {
    var group = [], end = -1, out = list.slice().sort(function (a, b) { return a.start - b.start || a.end - b.end; });
    var settleGroup = function () {
      var lane = [];
      group.forEach(function (a) { var i = 0; while (lane[i] > a.start) i++; lane[i] = a.end; a.lane = i; });
      group.forEach(function (a) { a.lanes = lane.length; });
    };
    out.forEach(function (a) {
      if (group.length && a.start >= end) { settleGroup(); group = []; end = -1; }
      group.push(a); end = Math.max(end, a.end);
    });
    if (group.length) settleGroup();
    return out;
  };

  var detail = function (a) {
    var box = $('cal-detail');
    box.hidden = false;
    box.innerHTML = '<span class="dot" style="background:' + (a.fresh ? 'var(--good)' : hueOf(a.pid)) + '"></span><div>' +
      '<b>' + esc(a.who) + (a.fresh ? '<span class="tagx good">New</span>' : '') + '</b>' +
      '<p>' + esc(a.t.name) + (a.t.price != null ? ' · ' + gbp(a.t.price) : '') + '</p>' +
      '<p>' + esc(dayShort(a.day)) + ', ' + hhmm(a.start) + '–' + hhmm(a.end) + (TEAM.length ? ' with ' + esc(staffName(a.pid)) : '') + '</p>' +
      '<p class="mute">Booked ' + (a.online ? 'online' : 'by phone') + ' ' + ago(a.made) + '. Confirmation and reminder texts sent.</p></div>' +
      '<button type="button" class="x" aria-label="Close">×</button>';
    box.querySelector('.x').onclick = function () { box.hidden = true; };
  };
  var block = function (a, top, k, cls) {
    var mini = a.lanes > 3;
    var b = el('button', 'bk' + (isPast(a) ? ' past' : '') + (a.fresh ? ' fresh' : '') + (cls ? ' ' + cls : '') + (mini ? ' mini' : ''));
    b.type = 'button';
    var h = Math.max(20, (a.end - a.start) * k - 2);
    b.style.top = (a.start - top) * k + 1 + 'px';
    b.style.height = h + 'px';
    if (a.lanes > 1) { b.style.left = 'calc(' + (a.lane / a.lanes * 100) + '% + 2px)'; b.style.width = 'calc(' + (100 / a.lanes) + '% - 4px)'; b.style.right = 'auto'; }
    paint(b, a.pid, a.fresh);
    b.innerHTML = '<b>' + hhmm(a.start) + ' ' + esc(a.who) + '</b>' + (h > 36 ? '<span>' + esc(a.t.name) + '</span>' : '') +
      (h > 52 && TEAM.length > 1 ? '<span>' + esc(staffName(a.pid)) + '</span>' : '');
    b.title = hhmm(a.start) + '–' + hhmm(a.end) + ' · ' + a.who + ' · ' + a.t.name + (TEAM.length ? ' · ' + staffName(a.pid) : '');
    /* too many side by side to read: a slim bar that still opens on tap */
    if (mini) { b.innerHTML = ''; b.setAttribute('aria-label', b.title); }
    b.onclick = function () { detail(a); };
    return b;
  };
  var hourLines = function (col, lo, hi, k) {
    for (var m = lo; m < hi; m += 60) { var l = el('div', 'hl'); l.style.top = (m - lo) * k + 'px'; col.appendChild(l); }
  };
  var axis = function (lo, hi, k) {
    var h = el('div', 'hrs'); h.style.height = (hi - lo) * k + 'px';
    for (var m = lo; m <= hi; m += 60) { var s = el('span', '', hhmm(m)); s.style.top = (m - lo) * k + 'px'; h.appendChild(s); }
    return h;
  };

  /* one day: a list on phones, a column per person on wide screens */
  var dayView = function (body) {
    var list = mine(apptsOn(cal.anchor)), sh = shiftsOn(cal.anchor);
    if (!sh.length) { body.innerHTML = '<div class="shut">Closed on ' + esc(DAYS[parse(cal.anchor).getDay()]) + 's</div>'; return; }
    if (!list.length) { body.innerHTML = '<div class="shut">Nothing booked yet</div>'; return; }
    var ag = el('div', 'agenda');
    list.forEach(function (a) {
      var live = a.day === TODAY && a.start <= nowMin && a.end > nowMin;
      var row = el('button', 'ap' + (isPast(a) ? ' past' : '') + (live ? ' now' : '') + (a.fresh ? ' fresh' : ''));
      row.type = 'button';
      row.innerHTML = '<span class="ap-t">' + hhmm(a.start) + '<small>' + (a.end - a.start) + ' min</small></span>' +
        '<span class="ap-c"><b>' + esc(a.who) + (a.fresh ? '<span class="tagx good">New</span>' : '') + (live ? '<span class="tagx">Now</span>' : '') + '</b>' +
        '<span>' + esc(a.t.name) + '</span>' +
        (TEAM.length > 1 ? '<span class="who">' + (coloured ? '<i class="dot" style="background:' + hueOf(a.pid) + '"></i>' : '') + esc(staffName(a.pid)) + '</span>' : '') + '</span>' +
        '<span class="ap-p">' + (a.t.price != null ? gbp(a.t.price) : '') + '<small>' + (a.online ? 'Online' : 'By phone') + '</small></span>';
      row.onclick = function () { detail(a); };
      ag.appendChild(row);
    });
    body.appendChild(ag);

    var ps = people();
    if (ps.length < 2) return;
    body.classList.add('has-cols');
    var lo = Math.floor(sh[0][0] / 60) * 60, hi = Math.ceil(sh[sh.length - 1][1] / 60) * 60, k = 1.05;
    var g = el('div', 'cols'); g.style.setProperty('--n', ps.length);
    g.appendChild(el('div', 'col-h', ''));
    ps.forEach(function (p) { g.appendChild(el('div', 'col-h', (coloured ? '<i class="dot" style="background:' + hueOf(p.id) + '"></i>' : '') + esc(p.name))); });
    g.appendChild(axis(lo, hi, k));
    ps.forEach(function (p) {
      var c = el('div', 'col'); c.style.height = (hi - lo) * k + 'px';
      sh.forEach(function (x) { var o = el('div', 'open'); o.style.top = (x[0] - lo) * k + 'px'; o.style.height = (x[1] - x[0]) * k + 'px'; c.appendChild(o); });
      hourLines(c, lo, hi, k);
      lanes(list.filter(function (a) { return a.pid === p.id; })).forEach(function (a) { c.appendChild(block(a, lo, k)); });
      if (cal.anchor === TODAY && nowMin > lo && nowMin < hi) { var n = el('div', 'nowl'); n.style.top = (nowMin - lo) * k + 'px'; c.appendChild(n); }
      g.appendChild(c);
    });
    body.appendChild(g);
  };

  /* a week on a time grid; on a phone it scrolls sideways, opened at today */
  var weekView = function (body) {
    var first = monday(cal.anchor), days = [], lo = 1440, hi = 0;
    for (var i = 0; i < 7; i++) days.push(shift(first, i));
    days.forEach(function (d) { shiftsOn(d).forEach(function (x) { lo = Math.min(lo, x[0]); hi = Math.max(hi, x[1]); }); });
    if (hi <= lo) { body.innerHTML = '<div class="shut">Closed all week</div>'; return; }
    lo = Math.floor(lo / 60) * 60; hi = Math.ceil(hi / 60) * 60;
    var k = 0.9;
    var wrap = el('div', 'wk'), g = el('div', 'wk-grid');
    g.appendChild(el('div', 'wk-h'));
    days.forEach(function (d) {
      var dd = parse(d), n = mine(apptsOn(d)).length, open = shiftsOn(d).length;
      var h = el('button', 'wk-h' + (d === TODAY ? ' today' : ''),
        '<i>' + DAYS[dd.getDay()].slice(0, 3) + '</i><b>' + dd.getDate() + '</b><em>' + (open ? n + ' booked' : 'Closed') + '</em>');
      h.type = 'button'; h.title = 'Open ' + dayShort(d);
      h.onclick = function () { cal.view = 'day'; cal.anchor = d; paintCal(); };
      g.appendChild(h);
    });
    g.appendChild(axis(lo, hi, k));
    days.forEach(function (d) {
      var c = el('div', 'col' + (d === TODAY ? ' today' : '')); c.style.height = (hi - lo) * k + 'px';
      shiftsOn(d).forEach(function (x) { var o = el('div', 'open'); o.style.top = (x[0] - lo) * k + 'px'; o.style.height = (x[1] - x[0]) * k + 'px'; c.appendChild(o); });
      hourLines(c, lo, hi, k);
      lanes(mine(apptsOn(d))).forEach(function (a) { c.appendChild(block(a, lo, k, 'thin')); });
      if (d === TODAY && nowMin > lo && nowMin < hi) { var n = el('div', 'nowl'); n.style.top = (nowMin - lo) * k + 'px'; c.appendChild(n); }
      g.appendChild(c);
    });
    wrap.appendChild(g);
    body.appendChild(wrap);
    var ti = days.indexOf(TODAY);
    if (ti > 0 && wrap.scrollWidth > wrap.clientWidth) {
      var colW = (g.scrollWidth - 44) / 7;
      wrap.scrollLeft = Math.max(0, ti * colW - colW * 0.25);
    }
  };

  /* a month: how full each day is, and a tap opens the day */
  var monthView = function (body) {
    var ms = monthStart(cal.anchor), m = parse(ms).getMonth(), first = monday(ms), cells = [];
    var d = first;
    do { for (var i = 0; i < 7; i++) { cells.push(d); d = shift(d, 1); } } while (parse(d).getMonth() === m);
    var counts = cells.map(function (x) { return parse(x).getMonth() === m ? mine(apptsOn(x)) : []; });
    var most = Math.max.apply(null, counts.map(function (c) { return c.length; }).concat([1]));
    var g = el('div', 'mo');
    ['Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat', 'Sun'].forEach(function (w) { g.appendChild(el('div', 'mo-w', w)); });
    var total = 0, takings = 0;
    cells.forEach(function (x, i) {
      var inMonth = parse(x).getMonth() === m, list = counts[i], open = shiftsOn(x).length;
      if (inMonth) { total += list.length; takings += sum(list); }
      var c = el('button', 'mc' + (inMonth ? '' : ' out') + (x === TODAY ? ' today' : '') + (open ? '' : ' shut'));
      c.type = 'button';
      c.innerHTML = '<span class="mc-d">' + parse(x).getDate() + '</span>' +
        (!inMonth ? '' : !open ? '<span class="mc-x">Closed</span>' : list.length
          ? '<span class="mc-n"><b>' + list.length + '</b><em> booked</em></span>' + (priced ? '<span class="mc-v">' + gbp(sum(list)) + '</span>' : '') +
            '<i class="mc-bar"><i style="width:' + Math.round(list.length / most * 100) + '%"></i></i>'
          : '<span class="mc-x">Free</span>');
      c.setAttribute('aria-label', dayShort(x) + ': ' + (open ? list.length + ' booked' : 'closed'));
      c.onclick = function () { cal.view = 'day'; cal.anchor = x; paintCal(); };
      g.appendChild(c);
    });
    body.appendChild(g);
    body.appendChild(el('p', 'mo-sum', '<b>' + total + '</b> appointments' + (priced ? ', <b>' + gbp(takings) + '</b>' : '') + ' in ' + MONTHS[m] + '. Tap a day to open it.'));
  };

  var paintKey = function () {
    var key = $('cal-key');
    key.innerHTML = '';
    if (TEAM.length < 2) { key.hidden = true; return; }
    key.hidden = false;
    [{ id: 'all', name: 'Everyone' }].concat(TEAM).forEach(function (p) {
      var b = el('button', 'kp', (p.id === 'all' || !coloured ? '' : '<i class="dot" style="background:' + hueOf(p.id) + '"></i>') + esc(p.name));
      b.type = 'button';
      b.setAttribute('aria-pressed', cal.who === p.id);
      b.onclick = function () { cal.who = p.id; paintCal(); };
      key.appendChild(b);
    });
  };

  var paintCal = function () {
    $('cal-label').textContent = label();
    Array.prototype.forEach.call($('cal-view').querySelectorAll('button'), function (b) { b.setAttribute('aria-checked', b.dataset.v === cal.view); });
    var here = cal.view === 'day' ? cal.anchor === TODAY : cal.view === 'week' ? monday(cal.anchor) === monday(TODAY) : monthStart(cal.anchor) === monthStart(TODAY);
    $('cal-today').disabled = here;
    paintKey();
    $('cal-detail').hidden = true;
    var body = $('cal-body');
    body.className = 'cal-body v-' + cal.view;
    body.innerHTML = '';
    if (cal.view === 'day') dayView(body);
    else if (cal.view === 'week') weekView(body);
    else monthView(body);
  };
  $('cal-view').addEventListener('click', function (e) {
    var b = e.target.closest('button'); if (!b) return;
    cal.view = b.dataset.v; paintCal();
  });
  $('cal-prev').onclick = function () { move(-1); };
  $('cal-next').onclick = function () { move(1); };
  $('cal-today').onclick = function () { cal.anchor = TODAY; paintCal(); };
  paintCal();
  var lastDW = window.innerWidth;
  window.addEventListener('resize', function () { if (window.innerWidth !== lastDW) { lastDW = window.innerWidth; paintCal(); } });

  /* ── latest bookings ──────────────────────────────────────────────────── */

  var recent = range(shift(TODAY, -14), 36).filter(function (a) { return a.made <= now; })
    .sort(function (a, b) { return b.made - a.made; }).slice(0, 7);
  $('feed').innerHTML = recent.map(function (a) {
    var late = a.online && closedAt(a.made);
    return '<li class="fd"><span class="av">' + esc(initials(a.who)) + '</span><div><p><b>' + esc(a.who) + '</b> booked ' + esc(a.t.name) +
      (a.fresh ? '<span class="tagx good">New</span>' : '') + '</p>' +
      '<span class="fd-m">' + esc(dayShort(a.day)) + ' at ' + hhmm(a.start) + (TEAM.length > 1 ? ' with ' + esc(staffName(a.pid)) : '') + ' · ' +
      (a.online ? 'online' : 'by phone') + ' ' + ago(a.made) + (late ? ' · at ' + clock(a.made) + ', while you were closed' : '') + '</span></div></li>';
  }).join('');

  /* ── takings by week ──────────────────────────────────────────────────── */

  var weeks = [];
  for (var w = 7; w >= 0; w--) {
    var start = shift(wk, -7 * w), xs = range(start, 7).filter(done);
    weeks.push({ start: start, n: xs.length, v: priced ? sum(xs) : xs.length, part: w === 0 });
  }
  var drawChart = function () {
    /* drawn at the size it is shown, so the labels stay 11px on a phone */
    var box = $('chart'), W = Math.max(280, Math.round(box.clientWidth || 600)), H = W < 480 ? 190 : 220, padL = 46, padB = 26, padT = 18;
    var max = Math.max.apply(null, weeks.map(function (x) { return x.v; })) || 1;
    var step = Math.pow(10, Math.floor(Math.log10(max / 3)));
    [1, 2, 2.5, 5, 10].some(function (m) { if (max / (step * m) <= 4) { step = step * m; return true; } return false; });
    var top = Math.ceil(max / step) * step;
    var y = function (v) { return padT + (H - padT - padB) * (1 - v / top); };
    var slot = (W - padL) / weeks.length, bw = Math.min(46, slot - 2 * 6);
    var fmt = function (v) { return priced ? gbp(v) : String(v); };
    var svg = '<svg viewBox="0 0 ' + W + ' ' + H + '" role="img" aria-label="' + esc(($('chart-t').textContent) + ': ' +
      weeks.map(function (x) { var d = parse(x.start); return d.getDate() + ' ' + MON[d.getMonth()] + ' ' + fmt(x.v); }).join(', ')) + '">';
    for (var g = 0; g <= top; g += step) {
      svg += '<line class="gl" x1="' + padL + '" x2="' + W + '" y1="' + y(g) + '" y2="' + y(g) + '"/>' +
        '<text class="ax" x="' + (padL - 8) + '" y="' + (y(g) + 4) + '" text-anchor="end">' + fmt(g) + '</text>';
    }
    var hi = 0;
    weeks.forEach(function (x, i) { if (x.v > weeks[hi].v) hi = i; });
    weeks.forEach(function (x, i) {
      var cx = padL + slot * i + slot / 2, x0 = cx - bw / 2, y0 = y(x.v), base = y(0), r = Math.min(4, (base - y0) / 2);
      var d = parse(x.start);
      svg += '<rect class="hit" data-i="' + i + '" x="' + (padL + slot * i) + '" y="' + padT + '" width="' + slot + '" height="' + (H - padT - padB) + '"/>';
      if (x.v > 0) {
        svg += '<path class="bar' + (x.part ? ' part' : '') + '" d="M' + x0 + ',' + base + 'V' + (y0 + r) + 'Q' + x0 + ',' + y0 + ' ' + (x0 + r) + ',' + y0 +
          'H' + (x0 + bw - r) + 'Q' + (x0 + bw) + ',' + y0 + ' ' + (x0 + bw) + ',' + (y0 + r) + 'V' + base + 'Z"/>';
      }
      if (i === hi || x.part) svg += '<text class="vl" x="' + cx + '" y="' + (y0 - 6) + '" text-anchor="middle">' + fmt(x.v) + '</text>';
      /* on a phone every other week is labelled, and always this one */
      if (W >= 480 || x.part || i % 2 === (weeks.length - 1) % 2)
        svg += '<text class="ax" x="' + (x.part ? Math.min(cx, W - 22) : cx) + '" y="' + (H - 8) + '" text-anchor="middle">' + (x.part ? 'This wk' : d.getDate() + ' ' + MON[d.getMonth()]) + '</text>';
    });
    svg += '</svg>';
    box.innerHTML = svg + '<div class="tip" id="tip" hidden></div>' +
      '<table class="sr"><caption>' + esc($('chart-t').textContent) + '</caption><tr><th>Week of</th><th>' + (priced ? 'Takings' : 'Appointments') + '</th></tr>' +
      weeks.map(function (x) { var d = parse(x.start); return '<tr><td>' + d.getDate() + ' ' + MON[d.getMonth()] + '</td><td>' + fmt(x.v) + '</td></tr>'; }).join('') + '</table>';
    var tip = $('tip'), sv = box.querySelector('svg');
    Array.prototype.forEach.call(box.querySelectorAll('.hit'), function (h) {
      var show = function () {
        var x = weeks[+h.dataset.i], d = parse(x.start), r = sv.getBoundingClientRect(), s = r.width / W;
        tip.hidden = false;
        tip.innerHTML = '<b>' + (x.part ? 'This week so far' : 'Week of ' + d.getDate() + ' ' + MON[d.getMonth()]) + '</b>' +
          (priced ? gbp(x.v) + ' · ' : '') + x.n + ' appointments';
        tip.style.left = ((+h.getAttribute('x') + slot / 2) * s) + 'px';
        tip.style.top = (y(x.v) * s) + 'px';
      };
      h.addEventListener('mouseenter', show);
      h.addEventListener('click', show);
      h.addEventListener('mouseleave', function () { tip.hidden = true; });
    });
  };
  $('chart-t').textContent = priced ? 'Takings by week' : 'Appointments by week';
  drawChart();
  var lastW = window.innerWidth;
  window.addEventListener('resize', function () { if (window.innerWidth !== lastW) { lastW = window.innerWidth; drawChart(); } });

  /* ── most booked this month ───────────────────────────────────────────── */

  var month = range(shift(TODAY, -29), 30), counts = {};
  month.forEach(function (a) { var k = a.t.name; (counts[k] = counts[k] || { n: 0, v: 0 }); counts[k].n++; counts[k].v += value(a); });
  var tops = Object.keys(counts).map(function (k) { return { name: k, n: counts[k].n, v: counts[k].v }; })
    .sort(function (a, b) { return b.n - a.n; }).slice(0, 5);
  var most = tops.length ? tops[0].n : 1;
  $('top').innerHTML = tops.map(function (t) {
    return '<li><div class="tp-l"><b title="' + esc(t.name) + '">' + esc(t.name) + '</b><span>' + t.n + (priced ? ' · ' + gbp(t.v) : '') + '</span></div>' +
      '<div class="meter" role="img" aria-label="' + esc(t.name) + ', ' + t.n + ' bookings"><i style="width:' + Math.round(t.n / most * 100) + '%"></i></div></li>';
  }).join('');

  /* ── booking link ─────────────────────────────────────────────────────── */

  var cp = $('copy');
  if (cp) cp.onclick = function () {
    var u = $('url').textContent;
    var ok = function () { cp.textContent = 'Copied'; setTimeout(function () { cp.textContent = 'Copy'; }, 1600); };
    if (navigator.clipboard && window.isSecureContext) navigator.clipboard.writeText(u).then(ok, function () {});
  };
})();
